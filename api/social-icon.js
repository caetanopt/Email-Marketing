module.exports = async (req, res) => {
  const nome = String((req.query && req.query.n) || '').toLowerCase().trim();
  const png = Object.prototype.hasOwnProperty.call(ICONES, nome) ? ICONES[nome] : null;
  if (!png) {
    // Cache curta: uma rede que ainda não existe aqui pode passar a existir,
    // e um 404 guardado durante um ano deixava-a partida para sempre.
    res.setHeader('Cache-Control', 'public, max-age=300');
    return res.status(404).json({ error: 'Ícone não encontrado' });
  }
  res.setHeader('Content-Type', 'image/png');
  res.setHeader('Content-Length', String(png.length));
  // O ícone de uma rede social não muda. Um ano, e imutável: um email aberto
  // três meses depois não volta a pedir isto ao servidor.
  res.setHeader('Cache-Control', 'public, max-age=31536000, immutable');
  res.setHeader('Access-Control-Allow-Origin', '*');
  return res.status(200).send(png);
};
